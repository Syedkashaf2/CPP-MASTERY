def _render_session_log(data: dict[str, Any]) -> str:
    comp = data["competence"]
    sessions = data["sessions"]
    rows = []
    for _, rec in sessions:
        a = rec.get("assessment", {})
        ev = rec.get("evidence", {})
        score = a.get("score_percent")
        score_str = f"{score}%" if score is not None else "Not scored"
        rows.append(
            [
                rec.get("date", ""),
                rec.get("session_id", ""),
                rec.get("record_type", ""),
                rec.get("attempt_type", ""),
                rec.get("hint_level", ""),
                rec.get("independence", {}).get("level", ""),
                ", ".join(rec.get("topic_ids", [])),
                ", ".join(rec.get("task_ids", [])),
                score_str,
                a.get("review_status", "pending"),
                ", ".join(ev.get("code_files", [])) or "—",
            ]
        )

    lines = [
        "<!-- GENERATED BY scripts/mastery_engine.py — DO NOT HAND-EDIT; update .mastery/records/ and run rebuild -->",
        "# C++ Learning Session History",
        "",
        f"- **Source As Of:** `{data['source_as_of']}`",
        f"- **Imported Session Records:** **{comp['total_sessions']}**",
        f"- **First-attempt H0:** {comp['first_attempt_h0']} | **Transfer H0:** {comp['transfer_h0']} | **Delayed H0:** {comp['delayed_h0']} | **Assisted (H1–H4):** {comp['assisted_total']} | **Remediation/Correction:** {comp['remediated_total']}",
        f"- **Mean H0 Score:** {comp['mean_h0_score'] if comp['mean_h0_score'] is not None else '—'}% | **Mean Assisted Score:** {comp['mean_assisted_score'] if comp['mean_assisted_score'] is not None else '—'}%",
        "",
        "Historical Stages 1–9.1 Task 2 evidence (`E-000A`–`E-041`, `R-001`–`R-008`) remains preserved read-only in `docs/baseline/`.",
        "",
        md_table(
            rows,
            [
                "Date",
                "Session ID",
                "Type",
                "Attempt",
                "Hint",
                "Independence",
                "Topics",
                "Tasks",
                "Score",
                "Review",
                "Code Files",
            ],
        )
        if rows
        else "_No new session records imported into `.mastery/records/sessions/` yet._",
        "",
    ]
    return "\n".join(lines)


def _render_mistake_ledger(data: dict[str, Any]) -> str:
    mist = data["mistakes"]
    patterns = mist["taxonomy_patterns"]

    pattern_rows = [
        [
            tax,
            stats["baseline_count"],
            stats["new_open"],
            stats["new_resolved"],
            stats["recurring_count"],
        ]
        for tax, stats in patterns.items()
    ]

    new_rows = [
        [
            m["mistake_id"],
            ", ".join(m.get("topic_ids", [])),
            m.get("taxonomy_class", ""),
            m.get("observable_symptom", ""),
            m.get("root_cause", ""),
            m.get("correction", ""),
            "Yes" if m.get("reproduced_independently") else "No",
            "Yes" if m.get("recurred") else "No",
            m.get("recurs_from_baseline_id") or "—",
            m.get("status", "open"),
        ]
        for m in mist["all_new"]
    ]

    lines = [
        "<!-- GENERATED BY scripts/mastery_engine.py — DO NOT HAND-EDIT; update .mastery/records/ and run rebuild -->",
        "# C++ Mistake and Remediation Ledger",
        "",
        f"- **Source As Of:** `{data['source_as_of']}`",
        "- **Historical Baseline (`M-001`–`M-019`):** Preserved read-only in `docs/baseline/CPP_LEARNING_PROGRESS_AND_RETENTION_AUDIT.md` (Section D) and `CPP_COGNITIVE_STATE_LEDGER.md` (Section C3).",
        f"- **New Mistakes (`M-020+`):** {len(mist['all_new'])} total ({len(mist['open_new'])} open/in-progress, {len(mist['recurring_new'])} recurring).",
        "",
        "## Failure-Class Pattern Aggregation (Baseline + New)",
        "",
        md_table(
            pattern_rows,
            ["C3 Taxonomy Class", "Baseline (M-001..019)", "New Open", "New Verified", "Recurring Instances"],
        ),
        "",
        "## New Mistake Records (`M-020+`)",
        "",
        md_table(
            new_rows,
            [
                "ID",
                "Topics",
                "Taxonomy Class",
                "Symptom",
                "Root Cause",
                "Correction",
                "Reproduced Indep.",
                "Recurred",
                "Baseline Link",
                "Status",
            ],
        )
        if new_rows
        else "_No new mistakes (`M-020+`) recorded yet._",
        "",
    ]
    return "\n".join(lines)


def _render_retention_log(data: dict[str, Any]) -> str:
    ret = data["retention"]

    def _rows(items: list[dict[str, Any]]) -> list[list[Any]]:
        return [
            [
                p["probe_id"],
                p["topic_id"],
                p["source_evidence_id"],
                f"+{p['interval_days']}d",
                p["scheduled_date"],
                p.get("effective_status", p["status"]),
                p.get("completed_date") or "—",
                p.get("hint_level") or "—",
                "Yes" if p.get("retention_verified") else "No",
                p.get("task_summary", ""),
            ]
            for p in items
        ]

    headers = [
        "Probe ID",
        "Topic",
        "Source Evidence",
        "Interval",
        "Scheduled",
        "Status",
        "Completed",
        "Hint",
        "Verified",
        "Task",
    ]
    short_rows = _rows(ret["short_all"])
    long_rows = _rows(ret["long_all"])

    lines = [
        "<!-- GENERATED BY scripts/mastery_engine.py — DO NOT HAND-EDIT; update .mastery/records/ and run rebuild -->",
        "# C++ Retention Record",
        "",
        f"- **Source As Of:** `{data['source_as_of']}` (Evaluation date: `{data['reference_date']}`)",
        f"- **Historical Baseline Short-Interval Probes (`R-001`–`R-008`):** {ret['baseline_short_completed']} completed in baseline audit (`[A]`); never conflated with long-term retention.",
        f"- **Short-Interval (`< 7 days`):** {ret['new_short_passed']} passed / {len(ret['short_pending'])} pending.",
        f"- **Long-Term (`>= 7 days`):** {ret['long_term_verified']} H0-verified / {len(ret['long_pending'])} pending.",
        "",
        "## Short-Interval Retrieval Probes (`1–3 days`)",
        "",
        md_table(short_rows, headers) if short_rows else "_No short-interval probes._",
        "",
        "## Long-Term Retention Probes (`7, 14, 30 days`)",
        "",
        md_table(long_rows, headers) if long_rows else "_No long-term probes._",
        "",
    ]
    return "\n".join(lines)


