def create_snapshot(paths: EnginePaths) -> Path:
    rebuild_docs(paths)
    render_dashboard_html(paths)
    data = build_analytics(paths)
    stamp = dt.datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    dest = paths.snapshots / stamp
    suffix = 1
    while dest.exists():
        dest = paths.snapshots / f"{stamp}-{suffix}"
        suffix += 1
    dest.mkdir(parents=True, exist_ok=False)

    for name in [
        "CURRENT_STATE.md",
        "SESSION_LOG.md",
        "MISTAKE_LEDGER.md",
        "RETENTION_LOG.md",
        "PROGRESS_REPORT.md",
        "MASTERY_DASHBOARD.html",
    ]:
        src = paths.progress / name
        if src.exists():
            (dest / name).write_bytes(src.read_bytes())

    for rec_file in (paths.mistake_ledger, paths.retention_state):
        if rec_file.exists():
            (dest / rec_file.name).write_bytes(rec_file.read_bytes())

    dump_json(
        dest / "snapshot_meta.json",
        {
            "created_at": now_utc_iso(),
            "source_as_of": data["source_as_of"],
            "session_record_count": data["competence"]["total_sessions"],
            "open_new_mistakes": len(data["mistakes"]["open_new"]),
            "long_term_verified_probes": data["retention"]["long_term_verified"],
        },
    )
    return dest
