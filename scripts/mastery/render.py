def render_markdown_outputs(paths: EnginePaths) -> dict[str, str]:
    data = build_analytics(paths)
    return {
        "CURRENT_STATE.md": _render_current_state(data),
        "SESSION_LOG.md": _render_session_log(data),
        "MISTAKE_LEDGER.md": _render_mistake_ledger(data),
        "RETENTION_LOG.md": _render_retention_log(data),
        "PROGRESS_REPORT.md": _render_progress_report(data),
    }


def rebuild_docs(paths: EnginePaths) -> dict[str, Path]:
    outputs = render_markdown_outputs(paths)
    paths.progress.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}
    for name, content in outputs.items():
        dest = paths.progress / name
        dest.write_text(content, encoding="utf-8")
        written[name] = dest
    return written


